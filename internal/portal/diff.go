package portal

import "strings"

// DiffLine is one line of a line diff.
type DiffLine struct {
	Op   string // "+", "-", " "
	Text string
}

const maxDiffLines = 1500

// lineDiff computes a line-based diff with a longest-common-subsequence
// table. Inputs beyond maxDiffLines lines are reported as unchanged-size
// replacements instead of consuming quadratic memory.
func lineDiff(oldText, newText string) (out []DiffLine, tooLarge bool) {
	a, b := splitLines(oldText), splitLines(newText)
	if len(a) > maxDiffLines || len(b) > maxDiffLines {
		return nil, true
	}
	lcs := make([][]int, len(a)+1)
	for i := range lcs {
		lcs[i] = make([]int, len(b)+1)
	}
	for i := len(a) - 1; i >= 0; i-- {
		for j := len(b) - 1; j >= 0; j-- {
			if a[i] == b[j] {
				lcs[i][j] = lcs[i+1][j+1] + 1
			} else {
				lcs[i][j] = max(lcs[i+1][j], lcs[i][j+1])
			}
		}
	}
	i, j := 0, 0
	for i < len(a) && j < len(b) {
		switch {
		case a[i] == b[j]:
			out = append(out, DiffLine{" ", a[i]})
			i++
			j++
		case lcs[i+1][j] >= lcs[i][j+1]:
			out = append(out, DiffLine{"-", a[i]})
			i++
		default:
			out = append(out, DiffLine{"+", b[j]})
			j++
		}
	}
	for ; i < len(a); i++ {
		out = append(out, DiffLine{"-", a[i]})
	}
	for ; j < len(b); j++ {
		out = append(out, DiffLine{"+", b[j]})
	}
	return out, false
}

func splitLines(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n")
}
